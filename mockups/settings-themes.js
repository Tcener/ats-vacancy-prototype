/* Настройки → Темы оформления.

   Карточка экрана: docs/reference/screens/settings-my.md

   Третий раздел настроек без подвкладок: одна страница на всю ширину
   острова, поэтому в SECTIONS описан через `pane`, а не `tabs`.

   Для модели данных раздел не даёт ничего — это чистое оформление.
   Перенесён ради полноты: без него раздел настроек остался бы
   с дыркой, к которой пришлось бы возвращаться.

   Одна вещь всё же любопытная: тема — настройка **организации**,
   а не человека. Она лежит в левой группе корня настроек, рядом
   с оргструктурой и безопасностью, то есть управляющий рекрутер
   выбирает оформление сразу всем. Личные настройки внешнего вида
   у Хантфлоу нет вовсе.

   Цвета взяты с боевого экрана, а не подобраны на глаз: у каждой
   темы сняты цвет сайдбара и акцента. Шапка у всех одна и та же
   чёрная — меняются только эти два.

   Подключается после settings.js. */

/* Тема: название, цвет сайдбара, цвет акцента.
   Порядок — как в оригинале, первая выбрана. */
const THEMES = [
  ['Гармоничная', '#000000', '#25cfe8'],
  ['Нежная', '#fadbe3', '#fe2d55'],
  ['Летний закат', '#fbb902', '#151319'],
  ['Чистая', '#ffffff', '#22bbd2'],
  ['Красное дерево', '#2b1a11', '#22bbd2'],
  ['Бриллианты', '#1d2441', '#5892c2'],
  ['Светлая', '#fcfcfc', '#db525e'],
  ['Энергичная', '#cfb2f5', '#faff6d'],
  ['Прогрессивная', '#ffc8cf', '#f0fe8a'],
  ['Новогодняя', '#2e0073', '#7ac016'],
];

/* Миниатюра приложения: чёрная полоса шапки сверху, цветной сайдбар
   слева, светлое поле содержимого и точка акцента. Ровно так устроено
   превью в оригинале — 154×91, радиус 10, полоса 10, сайдбар 36 */
const themeCard = ([name, side, accent], i) => `
  <li class="st-theme${i === 0 ? ' is-active' : ''}" data-od-id="theme-${i}">
    <button class="st-theme-btn" type="button" aria-pressed="${i === 0}">
      <span class="st-theme-preview" aria-hidden="true">
        <span class="st-theme-top"></span>
        <span class="st-theme-side" style="background:${side}"></span>
        <span class="st-theme-dot" style="background:${accent}"></span>
      </span>
      <span class="st-theme-name">${HF.esc(name)}</span>
    </button>
  </li>`;

const paneThemes = () => `
  <p class="st-plain-lead" data-od-id="themes-lead">Сделайте ваш Хантфлоу
    по‑настоящему уютным</p>
  <h3 class="st-plain-h3">Выберите вашу тему оформления</h3>
  <ul class="st-themes" data-od-id="themes-grid">
    ${THEMES.map(themeCard).join('')}
  </ul>`;

Object.assign(SECTIONS, {
  themes: { title: 'Темы оформления', pane: paneThemes },
});
